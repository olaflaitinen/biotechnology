# =============================================================================
#  POSITION IN THE CONTROLLED VOCABULARIES
# =============================================================================

# -----------------------------------------------------------------------------
#  MATURITY = ESTABLISHED.
#  PCR has been routine clinical practice for three decades and is performed
#  billions of times a year. Individual modalities inside the record are newer,
#  and metagenomic diagnosis would be EMERGING on its own, but the practice as
#  a whole is not.
# -----------------------------------------------------------------------------
MATURITY = Maturity.ESTABLISHED

# -----------------------------------------------------------------------------
#  RISK_TIER = REGULATED.
#  A commercial assay needs conformity assessment before it may be sold, and
#  the laboratory performing it needs accreditation. Two separate gates, held
#  by two separate bodies.
# -----------------------------------------------------------------------------
RISK_TIER = RiskTier.REGULATED

# -----------------------------------------------------------------------------
#  SCALE = BENCH.
#  The unit of work is one specimen. Population screening programmes are
#  population-scale activities built out of bench-scale tests, and the
#  distinction matters: the arithmetic in metrics.py is exactly what happens
#  when a bench-scale test is applied at population scale.
# -----------------------------------------------------------------------------
SCALE = Scale.BENCH

# -----------------------------------------------------------------------------
#  DOMAINS
#  HEALTH is the purpose. INFORMATION is included because a modern diagnostic
#  result is a data product: it is generated by a bioinformatic pipeline,
#  interpreted against a curated database, and stored as health data subject to
#  its own legal regime.
# -----------------------------------------------------------------------------
DOMAINS: Tuple[Domain, ...] = (Domain.HEALTH, Domain.INFORMATION)

REGULATORY_STATUS = RegulatoryStatus.AUTHORISED


