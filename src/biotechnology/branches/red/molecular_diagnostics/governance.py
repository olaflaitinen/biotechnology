#  `red/gene_therapy/governance.py`.
#
#  SUBTYPE-SPECIFIC NOTE
#  The governance of diagnostics turns on a distinction that has no equivalent
#  elsewhere in the red branch: the difference between a DEVICE placed on the
#  market and a TEST performed as a service.
#
#  A manufacturer selling a kit is regulated as a device maker. A hospital
#  laboratory that designs its own assay and runs it on its own patients has,
#  historically, not been. That gap is where most rare-disease and most
#  outbreak-response testing has always lived, because no manufacturer will
#  certify an assay for two hundred patients a year worldwide.
#
#  Both the European Union, through Regulation (EU) 2017/746, and the United
#  States have been closing that gap. The closure improves oversight and
#  simultaneously removes assays that will never be commercially viable. Both
#  halves of that sentence are true, and `practice.CHALLENGES` says so.
#
